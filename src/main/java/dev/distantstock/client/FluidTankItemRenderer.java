package dev.distantstock.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import dev.distantstock.DistantStock;
import dev.distantstock.item.PortableFluidTankItem;
import dev.distantstock.item.TankFluidColors;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.BlockEntityWithoutLevelRenderer;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.texture.TextureAtlas;
import net.minecraft.client.renderer.texture.TextureAtlasSprite;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.ItemDisplayContext;
import net.minecraft.world.item.ItemStack;
import net.neoforged.neoforge.client.extensions.common.IClientFluidTypeExtensions;
import net.neoforged.neoforge.fluids.FluidStack;

/**
 * Draws a tank's icon as its shell with the fluid actually in it.
 *
 * <p>The icon used to be a baked model: a window-shaped mask tinted by the fluid's colour. That gets
 * the colour right and everything else wrong -- water, tea and molten metal all came out as the same
 * flat blob, and a player reading a row of tanks in a chest could only tell them apart by hue. What
 * makes a fluid recognisable is its texture, so the texture is what gets drawn: the fluid's own
 * still sprite is sampled into the window, with the shell blended over it. That is per-stack work,
 * which no baked model can do, so the tanks render through this instead.
 *
 * <p>Everything here is drawn in a centred space: the 16x16 icon spans -0.5 to 0.5 and lies on the
 * plane vanilla's generated item models use. That is not the space the call arrives in, though --
 * {@code ItemRenderer} translates by (-0.5, -0.5, -0.5) before it hands the pose to a custom
 * renderer, so block space 0..1 is what comes in, and {@link #renderByItem} moves the origin to
 * the centre first (without that step every icon sat half a slot down and to the left of its own
 * slot). Nothing is scaled or rotated by hand -- those transforms come from the model JSON, which
 * is why the three tank models are now {@code builtin/entity} with the same display block as
 * {@code item/generated}.
 */
public final class FluidTankItemRenderer extends BlockEntityWithoutLevelRenderer {
    /** Where a flat item lies: 7.5/16 in model space, less the half-unit centring translate. */
    private static final float PLANE = 7.5f / 16f - 0.5f;
    /** A hair apart, so the shell blends over the fluid whatever order they are drawn in. */
    private static final float FLUID_Z = PLANE - 0.001f;
    private static final float SHELL_Z = PLANE + 0.001f;

    /**
     * The window in the shell texture, in its own pixels: columns 6..10, rows 6..12.
     *
     * <p>Public because the client smoke reads the shipped artwork at exactly this rectangle and
     * fails if the shell is not transparent there -- the art is generated by
     * {@code gen_fluid_tank_assets.py}, which asserts the same rectangle from the other side, and
     * between them the drawing and the code cannot drift apart silently.
     */
    public static final int WINDOW_X0 = 6;
    public static final int WINDOW_X1 = 10;
    public static final int WINDOW_TOP = 6;
    public static final int WINDOW_BOTTOM = 12;

    /** The same rectangle in the centred space this renderer draws in. */
    private static final float WIN_X0 = WINDOW_X0 / 16f - 0.5f;
    private static final float WIN_X1 = WINDOW_X1 / 16f - 0.5f;
    private static final float WIN_TOP = 1f - WINDOW_TOP / 16f - 0.5f;
    private static final float WIN_BOTTOM = 1f - WINDOW_BOTTOM / 16f - 0.5f;

    /** The patch of the fluid's texture that fills the window: a 4:6 slice from its middle. */
    private static final float PATCH_U0 = 0.25f;
    private static final float PATCH_U1 = 0.50f;
    private static final float PATCH_V0 = 0.25f;
    private static final float PATCH_V1 = 0.625f;

    private static final FluidTankItemRenderer INSTANCE = new FluidTankItemRenderer();

    private FluidTankItemRenderer() {
        // The dispatcher and model set are only used by renderers that draw block entities; this one
        // draws two quads and never touches them.
        super(null, null);
    }

    /** The one instance, registered as the client extension of all three tanks. */
    public static FluidTankItemRenderer instance() {
        return INSTANCE;
    }

    /** The shell texture a tank draws, named after its tier exactly as the item is. */
    public static ResourceLocation shellTexture(PortableFluidTankItem tank) {
        return ResourceLocation.fromNamespaceAndPath(DistantStock.MODID,
                "item/portable_fluid_tank_" + tank.tier().id());
    }

    /** The still sprite a fluid is drawn with, or null when it has none. */
    public static ResourceLocation stillTexture(FluidStack fluid) {
        if (fluid.isEmpty()) return null;
        return IClientFluidTypeExtensions.of(fluid.getFluidType()).getStillTexture(fluid);
    }

    /**
     * The filled band of the window, as {@code {bottom, top}} in icon space, or null when empty.
     *
     * <p>Level 1 fills the lower three rows of the six-row window and level 2 fills all of it, which
     * is what the old baked masks did -- the fluid reads as a level, not as a percentage, because at
     * this size anything finer is a lie.
     */
    public static float[] filledBand(int level) {
        if (level <= 0) return null;
        float rows = level >= 2 ? 3f / 8f : 3f / 16f;
        return new float[]{WIN_BOTTOM, WIN_BOTTOM + rows};
    }

    @Override
    public void renderByItem(ItemStack stack, ItemDisplayContext context, PoseStack pose,
                             MultiBufferSource buffers, int light, int overlay) {
        if (!(stack.getItem() instanceof PortableFluidTankItem tank)) return;
        pose.pushPose();
        // ItemRenderer translates by (-0.5, -0.5, -0.5) right before calling a custom renderer, so
        // the pose arrives in block space, 0..1, while everything below is written for the centred
        // space the class comment describes. Move the origin to the centre, or the icon's centre
        // lands on the slot's bottom-left corner and only its top-right quarter shows in the slot.
        pose.translate(0.5, 0.5, 0.5);
        try {
            FluidStack fluid = PortableFluidTankItem.fluid(stack);
            float[] band = filledBand(PortableFluidTankItem.fluidLevel(fluid, tank.capacity()));
            VertexConsumer out = buffers.getBuffer(RenderType.entityTranslucent(TextureAtlas.LOCATION_BLOCKS));
            var atlas = Minecraft.getInstance().getTextureAtlas(TextureAtlas.LOCATION_BLOCKS);
            // Read after pushPose: pose.last() must be this method's own (already translated) pose,
            // not the one the caller handed in.
            PoseStack.Pose pose1 = pose.last();

            if (band != null) {
                ResourceLocation still = stillTexture(fluid);
                if (still != null) {
                    TextureAtlasSprite sprite = atlas.apply(still);
                    // The band's share of the sampled patch, taken from the bottom of it: a half-full
                    // tank shows the lower half of the same fluid, not a squashed whole.
                    float share = (band[1] - band[0]) / (WIN_TOP - WIN_BOTTOM);
                    float v1 = PATCH_V1;
                    float v0 = PATCH_V1 - (PATCH_V1 - PATCH_V0) * share;
                    int tint = TankFluidColors.textureTint(fluid);
                    quad(out, pose1, WIN_X0, band[0], WIN_X1, band[1], FLUID_Z,
                            sprite.getU(PATCH_U0), sprite.getU(PATCH_U1),
                            sprite.getV(v0), sprite.getV(v1),
                            tint >> 16 & 0xFF, tint >> 8 & 0xFF, tint & 0xFF, tint >>> 24,
                            light, overlay);
                }
            }

            TextureAtlasSprite shell = atlas.apply(shellTexture(tank));
            quad(out, pose1, -0.5f, -0.5f, 0.5f, 0.5f, SHELL_Z,
                    shell.getU0(), shell.getU1(), shell.getV0(), shell.getV1(),
                    255, 255, 255, 255, light, overlay);
        } finally {
            pose.popPose();
        }
    }

    /** One flat quad, wound the way vanilla's generated item models are (top-left first). */
    private static void quad(VertexConsumer out, PoseStack.Pose pose,
                             float x0, float y0, float x1, float y1, float z,
                             float u0, float u1, float v0, float v1,
                             int r, int g, int b, int a, int light, int overlay) {
        out.addVertex(pose, x0, y1, z).setColor(r, g, b, a).setUv(u0, v0)
                .setOverlay(overlay).setLight(light).setNormal(pose, 0f, 0f, 1f);
        out.addVertex(pose, x1, y1, z).setColor(r, g, b, a).setUv(u1, v0)
                .setOverlay(overlay).setLight(light).setNormal(pose, 0f, 0f, 1f);
        out.addVertex(pose, x1, y0, z).setColor(r, g, b, a).setUv(u1, v1)
                .setOverlay(overlay).setLight(light).setNormal(pose, 0f, 0f, 1f);
        out.addVertex(pose, x0, y0, z).setColor(r, g, b, a).setUv(u0, v1)
                .setOverlay(overlay).setLight(light).setNormal(pose, 0f, 0f, 1f);
    }
}
